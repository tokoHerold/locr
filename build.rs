use std::{
    env,
    fs::{self, File},
    path::Path,
};

use serde::Deserialize;

#[derive(Deserialize)]
struct InferenceConfig {
    #[serde(rename = "PostProcess")]
    post_process: PostProcessConfig,
}

#[derive(Deserialize)]
struct PostProcessConfig {
    character_dict: Vec<String>,
}

#[cfg(feature = "paddleocr-rec-tiny")]
const MODEL_NAME: &str = "PP_OCRv6_tiny_rec";

#[cfg(feature = "paddleocr-rec-medium")]
const MODEL_NAME: &str = "PP_OCRv6_medium_rec";

#[cfg(all(feature = "paddleocr-rec-tiny", feature = "paddleocr-rec-medium"))]
compile_error!(
    "Multiple recognition models selected! Please enable only one of 'paddleocr-rec-tiny' or 'paddleocr-rec-medium'."
);

#[cfg(not(any(feature = "paddleocr-rec-tiny", feature = "paddleocr-rec-medium")))]
compile_error!(
    "No recognition model selected! Please enable either 'paddleocr-rec-tiny' or 'paddleocr-rec-medium'."
);

#[cfg(all(feature = "backend-ort", feature = "backend-burn"))]
compile_error!(
    "Both 'backend-ort' and 'backend-burn' are enabled! Please select exactly one inference backend."
);

#[cfg(not(any(feature = "backend-ort", feature = "backend-burn")))]
compile_error!(
    "No inference backend selected! Please enable either 'backend-ort' or 'backend-burn'."
);

pub fn main() {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR was not set by Cargo. Aborting...");
    let out_path = Path::new(&out_dir);

    let recognition_yaml_path = format!("data/models/{MODEL_NAME}_inference.yml");
    let recognition_onnx_path = format!("data/models/{MODEL_NAME}.onnx");

    println!("cargo:rerun-if-changed={recognition_yaml_path}");
    println!("cargo:rerun-if-changed={recognition_onnx_path}");

    // Parse dictionary from inference.yml
    let yaml_file = File::open(&recognition_yaml_path).expect(&format!("Failed to open {:}", recognition_yaml_path));
    let infrence_config: InferenceConfig =
        serde_saphyr::from_reader(yaml_file).expect(&format!("Failed to parse {:}", recognition_yaml_path));

    // Convert yaml content into array declaration
    let n_characters = infrence_config.post_process.character_dict.len() + 2; // CTC blank and space
    let mut code_character_dict = String::with_capacity(n_characters * 8 + 300);
    code_character_dict
        .push_str("/// Autogenerated static character dictionary compiled from `inference.yml`.\n");
    code_character_dict.push_str(&format!(
        "pub static CHARACTER_DICT: [char; {n_characters}] = [\n"
    ));
    code_character_dict.push_str("    \'_\',\n"); // CTC Blank (placeholder)
    for character in &infrence_config.post_process.character_dict {
        if character.chars().count() != 1 {
            panic!(
                "An entry in the inference character dict contained more than on character: {:}",
                character
            );
        }
        let actual_char: char = character.chars().next().unwrap();
        match actual_char {
            '\\' => {
                code_character_dict.push_str(&format!("    \'\\\\\',\n")); // Edge case: '\'
            }
            '\'' => {
                code_character_dict.push_str(&format!("    \'\\\'\',\n")); // Edge case: '\''
            }
            _ => {
                code_character_dict.push_str(&format!("    \'{actual_char}\',\n"));
            }
        }
    }
    code_character_dict.push_str("    \' \',\n"); // Space character
    code_character_dict.push_str("];\n");

    // Autogenerated model constants and embedded model bytes (private to module)
    #[cfg(feature = "backend-ort")]
    {
        code_character_dict.push_str(&format!(
            "\npub const RECOGNITION_MODEL_NAME: &str = \"{MODEL_NAME}\";\n"
        ));
        code_character_dict.push_str(&format!(
        "pub static RECOGNITION_MODEL_BYTES: &[u8] = include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{recognition_onnx_path}\"));\n"
    ));
    }

    fs::write(out_path.join("dictionary.rs"), code_character_dict)
        .expect("Failed to write autogenerated dictionary.rs");

    #[cfg(feature = "backend-burn")]
    {
        let det_onnx_path = "data/models/PP_OCRv6_tiny_det.onnx";
        use burn_onnx::{LoadStrategy, ModelGen};

        let burn_out_dir = out_path.join("burn_models");
        fs::create_dir_all(&burn_out_dir).expect("Failed to create burn_models directory");

        ModelGen::new()
            .input(&det_onnx_path)
            .out_dir(burn_out_dir.to_str().unwrap())
            .load_strategy(LoadStrategy::Embedded)
            .run_from_script();

        ModelGen::new()
            .input(&recognition_onnx_path)
            .out_dir(burn_out_dir.to_str().unwrap())
            .load_strategy(LoadStrategy::Embedded)
            .run_from_script();
    }
}
